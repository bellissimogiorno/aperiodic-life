  function constructPatch(H, T, P, F) {
    const rules = [
      ['H'],
      [0, 0, 'P', 2],
      [1, 0, 'H', 2],
      [2, 0, 'P', 2],
      [3, 0, 'H', 2],
      [4, 4, 'P', 2],
      [0, 4, 'F', 3],
      [2, 4, 'F', 3],
      [4, 1, 3, 2, 'F', 0],
      [8, 3, 'H', 0],
      [9, 2, 'P', 0],
      [10, 2, 'H', 0],
      [11, 4, 'P', 2],
      [12, 0, 'H', 2],
      [13, 0, 'F', 3],
      [14, 2, 'F', 1],
      [15, 3, 'H', 4],
      [8, 2, 'F', 1],
      [17, 3, 'H', 0],
      [18, 2, 'P', 0],
      [19, 2, 'H', 2],
      [20, 4, 'F', 3],
      [20, 0, 'P', 2],
      [22, 0, 'H', 2],
      [23, 4, 'F', 3],
      [23, 0, 'F', 3],
      [16, 0, 'P', 2],
      [9, 4, 0, 2, 'T', 2],
      [4, 0, 'F', 3],
    ];

    const result = new MetaTile([], H.width);
    const shapes = { H, T, P, F };

    for (const rule of rules) {
      if (rule.length === 1) {
        result.addChild(IDENT, shapes[rule[0]]);
      } else if (rule.length === 4) {
        const reference = result.children[rule[0]];
        const polygon = reference.geom.shape;
        const P0 = transformPoint(reference.T, polygon[(rule[1] + 1) % polygon.length]);
        const Q0 = transformPoint(reference.T, polygon[rule[1]]);
        const nextShape = shapes[rule[2]];
        const nextPolygon = nextShape.shape;
        result.addChild(
          matchTwo(
            nextPolygon[rule[3]],
            nextPolygon[(rule[3] + 1) % nextPolygon.length],
            P0,
            Q0,
          ),
          nextShape,
        );
      } else {
        const childP = result.children[rule[0]];
        const childQ = result.children[rule[2]];
        const P0 = transformPoint(childQ.T, childQ.geom.shape[rule[3]]);
        const Q0 = transformPoint(childP.T, childP.geom.shape[rule[1]]);
        const nextShape = shapes[rule[4]];
        const nextPolygon = nextShape.shape;
        result.addChild(
          matchTwo(
            nextPolygon[rule[5]],
            nextPolygon[(rule[5] + 1) % nextPolygon.length],
            P0,
            Q0,
          ),
          nextShape,
        );
      }
    }

    return result;
  }

  function constructMetatiles(patch) {
    const bps1 = patch.evalChild(8, 2);
    const bps2 = patch.evalChild(21, 2);
    const rotatedBps = transformPoint(rotateAbout(bps1, (-2 * PI) / 3), bps2);
    const p72 = patch.evalChild(7, 2);
    const p252 = patch.evalChild(25, 2);
    const lowerLeft = intersectLines(bps1, rotatedBps, patch.evalChild(6, 2), p72);

    let w = psub(patch.evalChild(6, 2), lowerLeft);
    const hOutline = [lowerLeft, bps1];
    w = transformPoint(rotation(-PI / 3), w);
    hOutline.push(padd(hOutline[1], w));
    hOutline.push(patch.evalChild(14, 2));
    w = transformPoint(rotation(-PI / 3), w);
    hOutline.push(psub(hOutline[3], w));
    hOutline.push(patch.evalChild(6, 2));

    const H = new MetaTile(hOutline, patch.width * 2);
    for (const child of [0, 9, 16, 27, 26, 6, 1, 8, 10, 15]) {
      H.addChild(patch.children[child].T, patch.children[child].geom);
    }

    const pOutline = [p72, padd(p72, psub(bps1, lowerLeft)), bps1, lowerLeft];
    const P = new MetaTile(pOutline, patch.width * 2);
    for (const child of [7, 2, 3, 4, 28]) {
      P.addChild(patch.children[child].T, patch.children[child].geom);
    }

    const fOutline = [
      bps2,
      patch.evalChild(24, 2),
      patch.evalChild(25, 0),
      p252,
      padd(p252, psub(lowerLeft, bps1)),
    ];
    const F = new MetaTile(fOutline, patch.width * 2);
    for (const child of [21, 20, 22, 23, 24, 25]) {
      F.addChild(patch.children[child].T, patch.children[child].geom);
    }

    const A = hOutline[2];
    const B = padd(hOutline[1], psub(hOutline[4], hOutline[5]));
    const C = transformPoint(rotateAbout(B, -PI / 3), A);
    const T = new MetaTile([B, C, A], patch.width * 2);
    T.addChild(patch.children[11].T, patch.children[11].geom);

    for (const meta of [H, P, F, T]) meta.recentre();
    return [H, T, P, F];
  }

  function countHats(geom) {
    if (geom.kind === 'hat') return 1;
    let count = 0;
    for (const child of geom.children) count += countHats(child.geom);
    return count;
  }

  function pairKey(a, b, base) {
    return a < b ? a * base + b : b * base + a;
  }

  function buildCSR(pairSet, count) {
    const degree = new Uint32Array(count);
    for (const key of pairSet) {
      const a = Math.floor(key / count);
      const b = key - a * count;
      degree[a]++;
      degree[b]++;
    }

    const offsets = new Uint32Array(count + 1);
    let maxDegree = 0;
    let sumDegree = 0;
    for (let i = 0; i < count; i++) {
      offsets[i + 1] = offsets[i] + degree[i];
      if (degree[i] > maxDegree) maxDegree = degree[i];
      sumDegree += degree[i];
    }

    const neighbors = new Uint32Array(offsets[count]);
    const cursor = offsets.slice(0, count);
    for (const key of pairSet) {
      const a = Math.floor(key / count);
      const b = key - a * count;
      neighbors[cursor[a]++] = b;
      neighbors[cursor[b]++] = a;
    }

    const histogram = new Uint32Array(maxDegree + 1);
    for (let i = 0; i < count; i++) histogram[degree[i]]++;

    return {
      offsets,
      neighbors,
      degree,
      maxDegree,
      averageDegree: count ? sumDegree / count : 0,
      edgeCount: pairSet.size,
      histogram,
    };
  }

  function computeBoundaryDistance(boundary, graph) {
    const n = boundary.length;
    const unseen = 0xffff;
    const distance = new Uint16Array(n);
    distance.fill(unseen);
    const queue = new Uint32Array(n);
    let head = 0;
    let tail = 0;

    for (let i = 0; i < n; i++) {
      if (boundary[i]) {
        distance[i] = 0;
        queue[tail++] = i;
      }
    }

    while (head < tail) {
      const cell = queue[head++];
      const nextDistance = distance[cell] + 1;
      for (let k = graph.offsets[cell]; k < graph.offsets[cell + 1]; k++) {
        const neighbor = graph.neighbors[k];
        if (distance[neighbor] === unseen) {
          distance[neighbor] = nextDistance;
          queue[tail++] = neighbor;
        }
      }
    }

    return distance;
  }

  function buildEinsteinPatch(depth) {
    if (!Number.isInteger(depth) || depth < 0 || depth > 6) {
      throw new RangeError('depth must be an integer from 0 to 6');
    }

    const started = typeof performance !== 'undefined' ? performance.now() : Date.now();
    let metatiles = makeInitialMetatiles();
    for (let i = 0; i < depth; i++) {
      metatiles = constructMetatiles(constructPatch(...metatiles));
    }
    const root = metatiles[0];
    const tileCount = countHats(root);
    const verticesPerTile = HAT_OUTLINE.length;
    const elementaryPointsPerTile = verticesPerTile + 1;
    const maxPointCount = tileCount * elementaryPointsPerTile;

    const transforms = new Float32Array(tileCount * 6);
    const vertices = new Float32Array(tileCount * verticesPerTile * 2);
    const centers = new Float32Array(tileCount * 2);
    const bboxes = new Float32Array(tileCount * 4);
    const labels = new Uint8Array(tileCount);
    const tileTypes = new Uint8Array(tileCount);
    const edgeBoundary = new Uint8Array(tileCount);
    const touchBoundary = new Uint8Array(tileCount);

    const pointMap = new Map();
    const pointHead = new Int32Array(maxPointCount);
    pointHead.fill(-1);
    const occurrenceTile = new Uint32Array(maxPointCount);
    const occurrenceNext = new Int32Array(maxPointCount);
    let pointCount = 0;
    let occurrenceCount = 0;

    const edgeOwner = new Map();
    const edgePairs = new Set();
    const edgeKeyBase = maxPointCount + 1;
    const coordinateBias = 1 << 20;
    const coordinateBase = 2 ** 21;

    let tileIndex = 0;
    let minX = Infinity;
    let minY = Infinity;
    let maxX = -Infinity;
    let maxY = -Infinity;

    // Reused by emitHat. Keeping these outside the per-tile path avoids four
    // short-lived allocations for every hat while preserving
    // first-seen lattice-point and edge insertion order.
    const vx = new Float64Array(verticesPerTile);
    const vy = new Float64Array(verticesPerTile);
    const vertexPointIds = new Uint32Array(verticesPerTile);
    const localPointIds = new Uint32Array(elementaryPointsPerTile);

    function pointId(x, y) {
      // The substitution is mathematically confined to this half-scale
      // triangular lattice. Affine construction uses binary64, so verify the
      // residual before snapping to the canonical integer coordinates.
      const rawQx = x * 4;
      const rawQy = (y / HALF_SQRT3) * 2;
      const qx = Math.round(rawQx);
      const qy = Math.round(rawQy);
      if (Math.abs(rawQx - qx) > 1e-6 || Math.abs(rawQy - qy) > 1e-6) {
        throw new Error('Hat vertex is not on the expected triangular lattice');
      }
      if (
        qx <= -coordinateBias ||
        qx >= coordinateBias ||
        qy <= -coordinateBias ||
        qy >= coordinateBias
      ) {
        throw new RangeError('Patch is too large for the lattice coordinate packing');
      }
      const key = (qx + coordinateBias) * coordinateBase + (qy + coordinateBias);
      let id = pointMap.get(key);
      if (id === undefined) {
        id = pointCount++;
        pointMap.set(key, id);
      }
      return id;
    }

    function addPointOccurrence(id, cell) {
      occurrenceTile[occurrenceCount] = cell;
      occurrenceNext[occurrenceCount] = pointHead[id];
      pointHead[id] = occurrenceCount;
      occurrenceCount++;
    }

    function emitHat(T, label) {
      const id = tileIndex++;
      transforms.set(T, id * 6);
      labels[id] = label === 'H1' ? 1 : label === 'H' ? 2 : label === 'T' ? 3 : label === 'P' ? 4 : 5;

      let cx = 0;
      let cy = 0;
      let localMinX = Infinity;
      let localMinY = Infinity;
      let localMaxX = -Infinity;
      let localMaxY = -Infinity;

      for (let i = 0; i < verticesPerTile; i++) {
        const p = HAT_OUTLINE[i];
        const x = T[0] * p.x + T[1] * p.y + T[2];
        const y = T[3] * p.x + T[4] * p.y + T[5];
        vx[i] = x;
        vy[i] = y;
        const vOffset = (id * verticesPerTile + i) * 2;
        vertices[vOffset] = x;
        vertices[vOffset + 1] = y;
        cx += x;
        cy += y;
        if (x < localMinX) localMinX = x;
        if (x > localMaxX) localMaxX = x;
        if (y < localMinY) localMinY = y;
        if (y > localMaxY) localMaxY = y;
      }

      centers[id * 2] = cx / verticesPerTile;
      centers[id * 2 + 1] = cy / verticesPerTile;
      const bboxOffset = id * 4;
      bboxes[bboxOffset] = localMinX;
      bboxes[bboxOffset + 1] = localMinY;
      bboxes[bboxOffset + 2] = localMaxX;
      bboxes[bboxOffset + 3] = localMaxY;
      if (localMinX < minX) minX = localMinX;
      if (localMaxX > maxX) maxX = localMaxX;
      if (localMinY < minY) minY = localMinY;
      if (localMaxY > maxY) maxY = localMaxY;

      let localPointCount = 0;
      const firstPoint = pointId(vx[0], vy[0]);
      vertexPointIds[0] = firstPoint;
      localPointIds[localPointCount++] = firstPoint;

      for (let i = 0; i < verticesPerTile; i++) {
        const j = (i + 1) % verticesPerTile;
        const ax = vx[i];
        const ay = vy[i];
        const bx = vx[j];
        const by = vy[j];
        const dx = bx - ax;
        const dy = by - ay;
        // Split the prototype's sole double-length side. Reflections preserve
        // outline indices, so this is exact and avoids a per-tile threshold.
        const parts = i === HAT_SPLIT_EDGE ? 2 : 1;

        let p0 = vertexPointIds[i];
        for (let part = 0; part < parts; part++) {
          let p1;
          if (part + 1 < parts) {
            const t1 = (part + 1) / parts;
            p1 = pointId(ax + dx * t1, ay + dy * t1);
            localPointIds[localPointCount++] = p1;
          } else if (j === 0) {
            p1 = firstPoint;
          } else {
            p1 = pointId(ax + dx, ay + dy);
            vertexPointIds[j] = p1;
            localPointIds[localPointCount++] = p1;
          }

          const a = p0 < p1 ? p0 : p1;
          const b = p0 < p1 ? p1 : p0;
          const key = a * edgeKeyBase + b;
          const owner = edgeOwner.get(key);
          if (owner === undefined) {
            edgeOwner.set(key, id);
          } else if (owner >= 0 && owner !== id) {
            edgePairs.add(pairKey(owner, id, tileCount));
            edgeOwner.set(key, -1);
          } else if (owner === id) {
            throw new Error('A hat repeats an elementary boundary segment');
          } else {
            throw new Error('More than two hats own an elementary boundary segment');
          }
          p0 = p1;
        }
      }

      if (localPointCount !== elementaryPointsPerTile) {
        throw new Error('Unexpected elementary point count for a hat');
      }
      for (let i = 0; i < localPointCount; i++) addPointOccurrence(localPointIds[i], id);
    }

    function visit(geom, parentTransform) {
      if (geom.kind === 'hat') {
        emitHat(parentTransform, geom.label);
        return;
      }
      for (const child of geom.children) {
        visit(child.geom, multiply(parentTransform, child.T));
      }
    }

    visit(root, IDENT);
    if (tileIndex !== tileCount) throw new Error('Internal tile count mismatch');

    // The two supported neighbourhoods have slightly different finite-patch
    // boundaries. For shared-edge adjacency, a boundary cell owns an exposed
    // elementary segment. For edge-or-corner adjacency, every tile incident
    // to an endpoint of an exposed segment is also a boundary cell, because
    // it can be missing neighbours beyond that point even when all its own
    // edges are paired.
    const boundaryPoint = new Uint8Array(pointCount);
    for (const [key, owner] of edgeOwner) {
      if (owner >= 0) {
        edgeBoundary[owner] = 1;
        const a = Math.floor(key / edgeKeyBase);
        const b = key - a * edgeKeyBase;
        boundaryPoint[a] = 1;
        boundaryPoint[b] = 1;
      }
    }

    const touchPairs = new Set(edgePairs);
    const incident = [];
    for (let p = 0; p < pointCount; p++) {
      incident.length = 0;
      for (let occurrence = pointHead[p]; occurrence >= 0; occurrence = occurrenceNext[occurrence]) {
        const tile = occurrenceTile[occurrence];
        incident.push(tile);
        if (boundaryPoint[p]) touchBoundary[tile] = 1;
      }
      for (let i = 0; i < incident.length; i++) {
        for (let j = i + 1; j < incident.length; j++) {
          if (incident[i] !== incident[j]) {
            touchPairs.add(pairKey(incident[i], incident[j], tileCount));
          }
        }
      }
    }

    const edgeGraph = buildCSR(edgePairs, tileCount);
    const touchGraph = buildCSR(touchPairs, tileCount);
    const edgeBoundaryDistance = computeBoundaryDistance(edgeBoundary, edgeGraph);
    const touchBoundaryDistance = computeBoundaryDistance(touchBoundary, touchGraph);
    // Keep each boundary definition and distance field with its graph so a
    // dead-border ring has consistent semantics under the selected contact
    // relation. The patch-level boundary aliases refer to the edge graph.
    edgeGraph.boundary = edgeBoundary;
    touchGraph.boundary = touchBoundary;
    edgeGraph.boundaryDistance = edgeBoundaryDistance;
    touchGraph.boundaryDistance = touchBoundaryDistance;

    let edgeBoundaryCount = 0;
    let touchBoundaryCount = 0;
    for (let i = 0; i < tileCount; i++) {
      edgeBoundaryCount += edgeBoundary[i];
      touchBoundaryCount += touchBoundary[i];
    }

    const ended = typeof performance !== 'undefined' ? performance.now() : Date.now();
    return {
      tiling: 'hat',
      tilingLabel: 'Einstein hat',
      seed: 'h-metatile',
      depth,
      tileCount,
      verticesPerTile,
      outline: HAT_OUTLINE,
      transforms,
      vertices,
      centers,
      bboxes,
      labels,
      tileTypes,
      typeCounts: { hat: tileCount },
      boundary: edgeBoundary,
      edgeBoundary,
      touchBoundary,
      boundaryDistance: edgeBoundaryDistance,
      edgeBoundaryDistance,
      touchBoundaryDistance,
      boundaryCount: edgeBoundaryCount,
      edgeBoundaryCount,
      touchBoundaryCount,
      edgeGraph,
      touchGraph,
      bounds: { minX, minY, maxX, maxY },
      buildMilliseconds: ended - started,
      latticePointCount: pointCount,
    };
  }

  function buildExactPolygonTopology(tilePointIds, tileCount, verticesPerTile, pointCount) {
    const edgePairs = new Set();
    const edgeOwner = new Map();
    const edgeKeyBase = pointCount + 1;
    const pointHead = new Int32Array(pointCount);
    pointHead.fill(-1);
    const occurrenceTile = new Uint32Array(tileCount * verticesPerTile);
    const occurrenceNext = new Int32Array(tileCount * verticesPerTile);
    let occurrenceCount = 0;

    for (let tile = 0; tile < tileCount; tile++) {
      const seen = new Set();
      const base = tile * verticesPerTile;
      for (let vertex = 0; vertex < verticesPerTile; vertex++) {
        const point = tilePointIds[base + vertex];
        if (point >= pointCount) throw new Error('Tile references an unknown exact point');
        if (seen.has(point)) throw new Error('Degenerate tile repeats an exact point');
        seen.add(point);
        occurrenceTile[occurrenceCount] = tile;
        occurrenceNext[occurrenceCount] = pointHead[point];
        pointHead[point] = occurrenceCount++;

        const next = tilePointIds[base + ((vertex + 1) % verticesPerTile)];
        const a = point < next ? point : next;
        const b = point < next ? next : point;
        const key = a * edgeKeyBase + b;
        const owner = edgeOwner.get(key);
        if (owner === undefined) {
          edgeOwner.set(key, tile);
        } else if (owner >= 0 && owner !== tile) {
          edgePairs.add(pairKey(owner, tile, tileCount));
          edgeOwner.set(key, -1);
        } else if (owner === -1) {
          throw new Error('More than two tiles own an exact edge');
        }
      }
    }

    const edgeBoundary = new Uint8Array(tileCount);
    const touchBoundary = new Uint8Array(tileCount);
    const boundaryPoint = new Uint8Array(pointCount);
    for (const [key, owner] of edgeOwner) {
      if (owner >= 0) {
        edgeBoundary[owner] = 1;
        const a = Math.floor(key / edgeKeyBase);
        const b = key - a * edgeKeyBase;
        boundaryPoint[a] = 1;
        boundaryPoint[b] = 1;
      }
    }

    const touchPairs = new Set(edgePairs);
    const incident = [];
    for (let point = 0; point < pointCount; point++) {
      incident.length = 0;
      for (
        let occurrence = pointHead[point];
        occurrence >= 0;
        occurrence = occurrenceNext[occurrence]
      ) {
        const tile = occurrenceTile[occurrence];
        incident.push(tile);
        if (boundaryPoint[point]) touchBoundary[tile] = 1;
      }
      for (let i = 0; i < incident.length; i++) {
        for (let j = i + 1; j < incident.length; j++) {
          if (incident[i] !== incident[j]) {
            touchPairs.add(pairKey(incident[i], incident[j], tileCount));
          }
        }
      }
    }

    const edgeGraph = buildCSR(edgePairs, tileCount);
    const touchGraph = buildCSR(touchPairs, tileCount);
    const edgeBoundaryDistance = computeBoundaryDistance(edgeBoundary, edgeGraph);
    const touchBoundaryDistance = computeBoundaryDistance(touchBoundary, touchGraph);
    edgeGraph.boundary = edgeBoundary;
    touchGraph.boundary = touchBoundary;
    edgeGraph.boundaryDistance = edgeBoundaryDistance;
    touchGraph.boundaryDistance = touchBoundaryDistance;

    let edgeBoundaryCount = 0;
    let touchBoundaryCount = 0;
    for (let tile = 0; tile < tileCount; tile++) {
      edgeBoundaryCount += edgeBoundary[tile];
      touchBoundaryCount += touchBoundary[tile];
    }

    return {
      edgeBoundary,
      touchBoundary,
      edgeBoundaryDistance,
      touchBoundaryDistance,
      edgeBoundaryCount,
      touchBoundaryCount,
      edgeGraph,
      touchGraph,
    };
  }

  function phiPowerPair(exponent) {
    let a = 1;
    let b = 0;
    for (let i = 0; i < exponent; i++) {
      const nextA = b;
      const nextB = a + b;
      a = nextA;
      b = nextB;
    }
    return [a, b];
  }

  function multiplyPhiPairs(a, b, c, d) {
    // (a + b*phi)(c + d*phi), using phi^2 = phi + 1.
    return [a * c + b * d, a * d + b * c + b * d];
  }

  class PenrosePointStore {
    constructor(depth) {
      this.coefficients = [];
      this.x = [];
      this.y = [];
      this.ids = new Map();
      this.scale = phiPowerPair(depth);
      // Interpolation revisits many vertices. Reuse its temporary coefficient
      // buffer and retain a copy only when a point is first encountered.
      this.scratch = new Int32Array(4);
      this.zero = this.intern(this.scratch);
    }

    get count() {
      return this.coefficients.length;
    }

    intern(values) {
      // Four signed 13-bit integers fit exactly in 52 bits of a binary64
      // number. The range checks make this an injective mixed-radix key;
      // larger coefficients use an exact string representation.
      // Map distinguishes number and string keys, so the fallback cannot
      // collide with a packed point. Geometry still uses the coefficients.
      const a = values[0] + 4096;
      const b = values[1] + 4096;
      const c = values[2] + 4096;
      const d = values[3] + 4096;
      const key =
        a >= 0 && a < 8192 && b >= 0 && b < 8192 &&
        c >= 0 && c < 8192 && d >= 0 && d < 8192
          ? ((a * 8192 + b) * 8192 + c) * 8192 + d
          : values.join(',');
      const existing = this.ids.get(key);
      if (existing !== undefined) return existing;

      const coefficients = Int32Array.from(values);
      const id = this.coefficients.length;
      const u = coefficients[0] + coefficients[1] * PHI;
      const v = coefficients[2] + coefficients[3] * PHI;
      const d0 = PENROSE_DIRECTIONS[0];
      const d1 = PENROSE_DIRECTIONS[1];
      const x = u * d0.x + v * d1.x;
      const y = u * d0.y + v * d1.y;
      this.ids.set(key, id);
      this.coefficients.push(coefficients);
      this.x.push(x);
      this.y.push(y);
      return id;
    }

    basis(index) {
      const normalized = ((index % 10) + 10) % 10;
      const sign = normalized < 5 ? 1 : -1;
      const direction = normalized % 5;
      const template = PENROSE_DIRECTION_COEFFICIENTS[direction];
      const values = this.scratch;
      for (let offset = 0; offset < 4; offset += 2) {
        const [a, b] = multiplyPhiPairs(
          this.scale[0],
          this.scale[1],
          template[offset],
          template[offset + 1],
        );
        values[offset] = sign * a;
        values[offset + 1] = sign * b;
      }
      return this.intern(values);
    }

    interpolateInversePhi(fromId, toId) {
      const from = this.coefficients[fromId];
      const to = this.coefficients[toId];
      const values = this.scratch;
      for (let offset = 0; offset < 4; offset += 2) {
        const deltaA = to[offset] - from[offset];
        const deltaB = to[offset + 1] - from[offset + 1];
        // (a + b*phi) / phi = (b - a) + a*phi.
        const nextA = from[offset] + deltaB - deltaA;
        const nextB = from[offset + 1] + deltaA;
        if (
          nextA < -0x80000000 || nextA > 0x7fffffff ||
          nextB < -0x80000000 || nextB > 0x7fffffff
        ) {
          throw new RangeError('Penrose exact coordinate exceeds the supported integer range');
        }
        values[offset] = nextA;
        values[offset + 1] = nextB;
      }
      return this.intern(values);
    }
  }

  function makePenroseWheel(store, seed) {
    const triangles = new Uint32Array(10 * 4);
    const mirrorOffset = seed === 'sun-mirror' ? 1 : 0;
    for (let i = 0; i < 10; i++) {
      let B = store.basis(i - 1);
      let C = store.basis(i);
      if ((i + mirrorOffset) % 2 === 0) {
        const swap = B;
        B = C;
        C = swap;
      }
      const offset = i * 4;
      triangles[offset] = 0;
      triangles[offset + 1] = store.zero;
      triangles[offset + 2] = B;
      triangles[offset + 3] = C;
    }
    return triangles;
  }

  function subdividePenroseTriangles(triangles, store) {
    let nextCount = 0;
    for (let offset = 0; offset < triangles.length; offset += 4) {
      nextCount += triangles[offset] === 0 ? 2 : 3;
    }
    const result = new Uint32Array(nextCount * 4);
    let write = 0;

    function emit(kind, A, B, C) {
      result[write++] = kind;
      result[write++] = A;
      result[write++] = B;
      result[write++] = C;
    }

    for (let offset = 0; offset < triangles.length; offset += 4) {
      const kind = triangles[offset];
      const A = triangles[offset + 1];
      const B = triangles[offset + 2];
      const C = triangles[offset + 3];
      if (kind === 0) {
        const P = store.interpolateInversePhi(A, B);
        emit(0, C, P, B);
        emit(1, P, C, A);
      } else {
        const Q = store.interpolateInversePhi(B, A);
        const R = store.interpolateInversePhi(B, C);
        emit(1, R, C, A);
        emit(1, Q, R, B);
        emit(0, R, Q, A);
      }
    }
    return result;
  }

  function buildPenrosePatch(depth, options = {}) {
    if (!Number.isInteger(depth) || depth < 1 || depth > 11) {
      throw new RangeError('depth must be an integer from 1 to 11');
    }
    const seed = typeof options === 'string' ? options : options.seed || 'sun';
    if (seed !== 'sun' && seed !== 'sun-mirror') {
      throw new RangeError('Penrose seed must be "sun" or "sun-mirror"');
    }

    const started = typeof performance !== 'undefined' ? performance.now() : Date.now();
    const store = new PenrosePointStore(depth);
    let triangles = makePenroseWheel(store, seed);
    for (let i = 0; i < depth; i++) {
      triangles = subdividePenroseTriangles(triangles, store);
    }

    const triangleCount = triangles.length / 4;
    const pointKeyBase = store.count + 1;
    const seamOwner = new Map();
    const pairA = [];
    const pairB = [];

    for (let triangle = 0; triangle < triangleCount; triangle++) {
      const offset = triangle * 4;
      const B = triangles[offset + 2];
      const C = triangles[offset + 3];
      const a = B < C ? B : C;
      const b = B < C ? C : B;
      const key = a * pointKeyBase + b;
      const owner = seamOwner.get(key);
      if (owner === undefined) {
        seamOwner.set(key, triangle);
      } else if (owner >= 0) {
        if (triangles[owner * 4] !== triangles[offset]) {
          throw new Error('Penrose mirror seam joins different triangle kinds');
        }
        pairA.push(owner);
        pairB.push(triangle);
        seamOwner.set(key, -1);
      } else {
        throw new Error('More than two Penrose triangles share a mirror seam');
      }
    }

    let unmatchedHalfTriangles = 0;
    for (const owner of seamOwner.values()) if (owner >= 0) unmatchedHalfTriangles++;

    const tileCount = pairA.length;
    const verticesPerTile = 4;
    const transforms = new Float32Array(tileCount * 6);
    const vertices = new Float32Array(tileCount * verticesPerTile * 2);
    const centers = new Float32Array(tileCount * 2);
    const bboxes = new Float32Array(tileCount * 4);
    const tileTypes = new Uint8Array(tileCount);
    const pointIds = new Uint32Array(tileCount * verticesPerTile);

    let thinCount = 0;
    let thickCount = 0;
    let minX = Infinity;
    let minY = Infinity;
    let maxX = -Infinity;
    let maxY = -Infinity;

    for (let tile = 0; tile < tileCount; tile++) {
      const firstOffset = pairA[tile] * 4;
      const secondOffset = pairB[tile] * 4;
      const kind = triangles[firstOffset];
      const A1 = triangles[firstOffset + 1];
      const B1 = triangles[firstOffset + 2];
      const C1 = triangles[firstOffset + 3];
      const A2 = triangles[secondOffset + 1];
      const B2 = triangles[secondOffset + 2];
      const C2 = triangles[secondOffset + 3];
      if (!((B1 === B2 && C1 === C2) || (B1 === C2 && C1 === B2))) {
        throw new Error('Paired Penrose triangles do not share the same exact seam');
      }

      let v0 = A1;
      let v1 = B1;
      const v2 = A2;
      let v3 = C1;
      const signedArea2 =
        store.x[v0] * store.y[v1] - store.x[v1] * store.y[v0] +
        store.x[v1] * store.y[v2] - store.x[v2] * store.y[v1] +
        store.x[v2] * store.y[v3] - store.x[v3] * store.y[v2] +
        store.x[v3] * store.y[v0] - store.x[v0] * store.y[v3];
      if (signedArea2 < 0) {
        const swap = v1;
        v1 = v3;
        v3 = swap;
      }

      const ids = [v0, v1, v2, v3];
      const x0 = store.x[v0];
      const y0 = store.y[v0];
      const x1 = store.x[v1];
      const y1 = store.y[v1];
      const x2 = store.x[v2];
      const y2 = store.y[v2];
      const x3 = store.x[v3];
      const y3 = store.y[v3];
      if (Math.hypot(x0 + x2 - x1 - x3, y0 + y2 - y1 - y3) > 1e-8) {
        throw new Error('Paired Penrose triangles do not form a parallelogram');
      }

      transforms.set([x1 - x0, x3 - x0, x0, y1 - y0, y3 - y0, y0], tile * 6);
      let localMinX = Infinity;
      let localMinY = Infinity;
      let localMaxX = -Infinity;
      let localMaxY = -Infinity;
      let cx = 0;
      let cy = 0;
      for (let vertex = 0; vertex < verticesPerTile; vertex++) {
        const point = ids[vertex];
        const x = store.x[point];
        const y = store.y[point];
        const vertexOffset = (tile * verticesPerTile + vertex) * 2;
        vertices[vertexOffset] = x;
        vertices[vertexOffset + 1] = y;
        pointIds[tile * verticesPerTile + vertex] = point;
        cx += x;
        cy += y;
        if (x < localMinX) localMinX = x;
        if (x > localMaxX) localMaxX = x;
        if (y < localMinY) localMinY = y;
        if (y > localMaxY) localMaxY = y;
      }
      centers[tile * 2] = cx / verticesPerTile;
      centers[tile * 2 + 1] = cy / verticesPerTile;
      bboxes.set([localMinX, localMinY, localMaxX, localMaxY], tile * 4);
      if (localMinX < minX) minX = localMinX;
      if (localMaxX > maxX) maxX = localMaxX;
      if (localMinY < minY) minY = localMinY;
      if (localMaxY > maxY) maxY = localMaxY;
      tileTypes[tile] = kind;
      if (kind === 0) thinCount++;
      else thickCount++;
    }

    const topology = buildExactPolygonTopology(
      pointIds,
      tileCount,
      verticesPerTile,
      store.count,
    );
    const ended = typeof performance !== 'undefined' ? performance.now() : Date.now();
    return {
      tiling: 'penrose',
      tilingLabel: 'Penrose P3 rhombs',
      seed,
      depth,
      tileCount,
      triangleCount,
      unmatchedHalfTriangles,
      verticesPerTile,
      outline: PENROSE_OUTLINE,
      transforms,
      vertices,
      centers,
      bboxes,
      labels: tileTypes,
      tileTypes,
      tilePointIds: pointIds,
      typeCounts: { thin: thinCount, thick: thickCount },
      boundary: topology.edgeBoundary,
      edgeBoundary: topology.edgeBoundary,
      touchBoundary: topology.touchBoundary,
      boundaryDistance: topology.edgeBoundaryDistance,
      edgeBoundaryDistance: topology.edgeBoundaryDistance,
      touchBoundaryDistance: topology.touchBoundaryDistance,
      boundaryCount: topology.edgeBoundaryCount,
      edgeBoundaryCount: topology.edgeBoundaryCount,
      touchBoundaryCount: topology.touchBoundaryCount,
      edgeGraph: topology.edgeGraph,
      touchGraph: topology.touchGraph,
      bounds: { minX, minY, maxX, maxY },
      buildMilliseconds: ended - started,
      latticePointCount: store.count,
      exactPointCount: store.count,
    };
  }

  function buildSquarePatch(size) {
    if (!Number.isInteger(size) || size < 3 || size > 511) {
      throw new RangeError('square size must be an integer from 3 to 511');
    }

    const started = typeof performance !== 'undefined' ? performance.now() : Date.now();
    const tileCount = size * size;
    const verticesPerTile = SQUARE_OUTLINE.length;
    const transforms = new Float32Array(tileCount * 6);
    const vertices = new Float32Array(tileCount * verticesPerTile * 2);
    const centers = new Float32Array(tileCount * 2);
    const bboxes = new Float32Array(tileCount * 4);
    const tileTypes = new Uint8Array(tileCount);
    const coordinates = new Int32Array(tileCount * 2);
    const edgeBoundary = new Uint8Array(tileCount);
    const touchBoundary = new Uint8Array(tileCount);
    const edgePairs = new Set();
    const touchPairs = new Set();
    const origin = -size / 2;

    for (let row = 0; row < size; row++) {
      for (let column = 0; column < size; column++) {
        const tile = row * size + column;
        const x = origin + column;
        const y = origin + row;
        transforms.set([1, 0, x, 0, 1, y], tile * 6);
        centers[tile * 2] = x + 0.5;
        centers[tile * 2 + 1] = y + 0.5;
        bboxes.set([x, y, x + 1, y + 1], tile * 4);
        coordinates[tile * 2] = column - Math.floor(size / 2);
        coordinates[tile * 2 + 1] = row - Math.floor(size / 2);
        for (let vertex = 0; vertex < verticesPerTile; vertex++) {
          const local = SQUARE_OUTLINE[vertex];
          const offset = (tile * verticesPerTile + vertex) * 2;
          vertices[offset] = x + local.x;
          vertices[offset + 1] = y + local.y;
        }
        const boundary = row === 0 || column === 0 || row === size - 1 || column === size - 1;
        if (boundary) {
          edgeBoundary[tile] = 1;
          touchBoundary[tile] = 1;
        }
        if (column + 1 < size) {
          const neighbor = tile + 1;
          const key = pairKey(tile, neighbor, tileCount);
          edgePairs.add(key);
          touchPairs.add(key);
        }
        if (row + 1 < size) {
          const neighbor = tile + size;
          const key = pairKey(tile, neighbor, tileCount);
          edgePairs.add(key);
          touchPairs.add(key);
          if (column > 0) touchPairs.add(pairKey(tile, neighbor - 1, tileCount));
          if (column + 1 < size) touchPairs.add(pairKey(tile, neighbor + 1, tileCount));
        }
      }
    }

    const edgeGraph = buildCSR(edgePairs, tileCount);
    const touchGraph = buildCSR(touchPairs, tileCount);
    const edgeBoundaryDistance = computeBoundaryDistance(edgeBoundary, edgeGraph);
    const touchBoundaryDistance = computeBoundaryDistance(touchBoundary, touchGraph);
    edgeGraph.boundary = edgeBoundary;
    touchGraph.boundary = touchBoundary;
    edgeGraph.boundaryDistance = edgeBoundaryDistance;
    touchGraph.boundaryDistance = touchBoundaryDistance;
    let boundaryCount = 0;
    for (const value of edgeBoundary) boundaryCount += value;
    const ended = typeof performance !== 'undefined' ? performance.now() : Date.now();

    return {
      tiling: 'square',
      tilingLabel: 'Square grid',
      seed: 'centered-square',
      depth: size,
      size,
      width: size,
      height: size,
      tileCount,
      verticesPerTile,
      outline: SQUARE_OUTLINE,
      transforms,
      vertices,
      centers,
      bboxes,
      labels: tileTypes,
      tileTypes,
      coordinates,
      typeCounts: { square: tileCount },
      boundary: edgeBoundary,
      edgeBoundary,
      touchBoundary,
      boundaryDistance: edgeBoundaryDistance,
      edgeBoundaryDistance,
      touchBoundaryDistance,
      boundaryCount,
      edgeBoundaryCount: boundaryCount,
      touchBoundaryCount: boundaryCount,
      edgeGraph,
      touchGraph,
      bounds: { minX: origin, minY: origin, maxX: origin + size, maxY: origin + size },
      buildMilliseconds: ended - started,
      latticePointCount: (size + 1) * (size + 1),
      pickingCellSize: 1,
    };
  }

  function buildHexPatch(radius) {
    if (!Number.isInteger(radius) || radius < 1 || radius > 256) {
      throw new RangeError('hex radius must be an integer from 1 to 256');
    }

    const started = typeof performance !== 'undefined' ? performance.now() : Date.now();
    const axial = [];
    const idByCoordinate = new Map();
    for (let q = -radius; q <= radius; q++) {
      const rMinimum = Math.max(-radius, -q - radius);
      const rMaximum = Math.min(radius, -q + radius);
      for (let r = rMinimum; r <= rMaximum; r++) {
        const id = axial.length;
        axial.push([q, r]);
        idByCoordinate.set(`${q},${r}`, id);
      }
    }

    const tileCount = axial.length;
    const verticesPerTile = HEX_OUTLINE.length;
    const transforms = new Float32Array(tileCount * 6);
    const vertices = new Float32Array(tileCount * verticesPerTile * 2);
    const centers = new Float32Array(tileCount * 2);
    const bboxes = new Float32Array(tileCount * 4);
    const tileTypes = new Uint8Array(tileCount);
    const coordinates = new Int32Array(tileCount * 2);
    const edgeBoundary = new Uint8Array(tileCount);
    const touchBoundary = new Uint8Array(tileCount);
    const edgePairs = new Set();
    const directions = [[1, 0], [1, -1], [0, -1], [-1, 0], [-1, 1], [0, 1]];
    let minX = Infinity;
    let minY = Infinity;
    let maxX = -Infinity;
    let maxY = -Infinity;

    for (let tile = 0; tile < tileCount; tile++) {
      const [q, r] = axial[tile];
      const x = SQRT3 * (q + r / 2);
      const y = 1.5 * r;
      transforms.set([1, 0, x, 0, 1, y], tile * 6);
      centers[tile * 2] = x;
      centers[tile * 2 + 1] = y;
      coordinates[tile * 2] = q;
      coordinates[tile * 2 + 1] = r;
      let localMinX = Infinity;
      let localMinY = Infinity;
      let localMaxX = -Infinity;
      let localMaxY = -Infinity;
      for (let vertex = 0; vertex < verticesPerTile; vertex++) {
        const local = HEX_OUTLINE[vertex];
        const vx = x + local.x;
        const vy = y + local.y;
        const offset = (tile * verticesPerTile + vertex) * 2;
        vertices[offset] = vx;
        vertices[offset + 1] = vy;
        if (vx < localMinX) localMinX = vx;
        if (vx > localMaxX) localMaxX = vx;
        if (vy < localMinY) localMinY = vy;
        if (vy > localMaxY) localMaxY = vy;
      }
      bboxes.set([localMinX, localMinY, localMaxX, localMaxY], tile * 4);
      if (localMinX < minX) minX = localMinX;
      if (localMinY < minY) minY = localMinY;
      if (localMaxX > maxX) maxX = localMaxX;
      if (localMaxY > maxY) maxY = localMaxY;
      if (Math.max(Math.abs(q), Math.abs(r), Math.abs(-q - r)) === radius) {
        edgeBoundary[tile] = 1;
        touchBoundary[tile] = 1;
      }
      for (const [dq, dr] of directions) {
        const neighbor = idByCoordinate.get(`${q + dq},${r + dr}`);
        if (neighbor !== undefined && tile < neighbor) edgePairs.add(pairKey(tile, neighbor, tileCount));
      }
    }

    // In the regular honeycomb tiling, every pair of hexagons meeting at a
    // vertex also shares an edge, so edge and touch neighbourhoods coincide.
    const touchPairs = new Set(edgePairs);
    const edgeGraph = buildCSR(edgePairs, tileCount);
    const touchGraph = buildCSR(touchPairs, tileCount);
    const edgeBoundaryDistance = computeBoundaryDistance(edgeBoundary, edgeGraph);
    const touchBoundaryDistance = computeBoundaryDistance(touchBoundary, touchGraph);
    edgeGraph.boundary = edgeBoundary;
    touchGraph.boundary = touchBoundary;
    edgeGraph.boundaryDistance = edgeBoundaryDistance;
    touchGraph.boundaryDistance = touchBoundaryDistance;
    let boundaryCount = 0;
    for (const value of edgeBoundary) boundaryCount += value;
    const ended = typeof performance !== 'undefined' ? performance.now() : Date.now();

    return {
      tiling: 'hex',
      tilingLabel: 'Hexagonal grid',
      seed: 'centered-hexagon',
      depth: radius,
      radius,
      tileCount,
      verticesPerTile,
      outline: HEX_OUTLINE,
      transforms,
      vertices,
      centers,
      bboxes,
      labels: tileTypes,
      tileTypes,
      coordinates,
      typeCounts: { hex: tileCount },
      boundary: edgeBoundary,
      edgeBoundary,
      touchBoundary,
      boundaryDistance: edgeBoundaryDistance,
      edgeBoundaryDistance,
      touchBoundaryDistance,
      boundaryCount,
      edgeBoundaryCount: boundaryCount,
      touchBoundaryCount: boundaryCount,
      edgeGraph,
      touchGraph,
      bounds: { minX, minY, maxX, maxY },
      buildMilliseconds: ended - started,
      latticePointCount: 6 * (radius + 1) ** 2,
      pickingCellSize: 2,
    };
  }

  function buildPatch(tiling, depth, options = {}) {
    const normalized = String(tiling || 'hat').toLowerCase();
    if (normalized === 'square' || normalized === 'square-grid') return buildSquarePatch(depth);
    if (normalized === 'hex' || normalized === 'hexagonal' || normalized === 'hex-grid') return buildHexPatch(depth);
    if (normalized === 'hat' || normalized === 'einstein') return buildEinsteinPatch(depth);
    if (normalized === 'penrose' || normalized === 'penrose-p3') {
      return buildPenrosePatch(depth, options);
    }
    throw new RangeError(`Unknown tiling ${JSON.stringify(tiling)}`);
  }

  function clampInteger(value, minimum, maximum, fallback) {
    const number = Number(value);
    if (!Number.isFinite(number)) return fallback;
    return Math.max(minimum, Math.min(maximum, Math.trunc(number)));
  }

  function parseCountList(raw) {
    let text = String(raw);
    if (!text) return [];

    let delimited = text.includes(',') || text.includes(';');
    const bracketPairs = { '[': ']', '(': ')', '{': '}' };
    const expectedCloser = bracketPairs[text[0]];
    if (expectedCloser) {
      if (text[text.length - 1] !== expectedCloser) {
        throw new Error('Mismatched brackets in neighbour-count list');
      }
      text = text.slice(1, -1);
      delimited = true;
    } else if (/[\[\](){}]/.test(text)) {
      throw new Error('Brackets must enclose an entire neighbour-count list');
    }

    if (!text) return [];
    const tokens = delimited ? text.split(/[,;]/) : [...text];
    if (!tokens.length || tokens.some((token) => !/^\d+$/.test(token))) {
      throw new Error('Neighbour counts must be integers from 0 to 255');
    }
    const values = tokens.map(Number);
    if (values.some((value) => value < 0 || value > 255)) {
      throw new Error('Neighbour counts must be integers from 0 to 255');
    }
    return [...new Set(values)].sort((a, b) => a - b);
  }

  function formatCountList(values) {
    return values.some((value) => value >= 10)
      ? `[${values.join(',')}]`
      : values.join('');
  }

  function formatRule(birth, survive) {
    function normalizedCounts(values, label) {
      if (values === null || values === undefined || typeof values[Symbol.iterator] !== 'function') {
        throw new TypeError(`${label} counts must be iterable`);
      }
      const counts = [...values];
      if (counts.some((value) => !Number.isInteger(value) || value < 0 || value > 255)) {
        throw new RangeError(`${label} counts must be integers from 0 to 255`);
      }
      return [...new Set(counts)].sort((left, right) => left - right);
    }
    const births = normalizedCounts(birth, 'Birth');
    const survivals = normalizedCounts(survive, 'Survival');
    return `B${formatCountList(births)}/S${formatCountList(survivals)}`;
  }

  function parseRule(text, maxDegree = 255) {
    if (!Number.isInteger(maxDegree) || maxDegree < 0 || maxDegree > 255) {
      throw new RangeError('maxDegree must be an integer from 0 to 255');
    }
    const normalized = String(text).toUpperCase().replace(/\s+/g, '');
    const match = /^B([^/]*)\/S(.*)$/.exec(normalized);
    if (!match) {
      throw new Error('Use B…/S… notation, for example B3/S23, B2,4/S1,2,3, or B[10]/S[9,10]');
    }
    const birth = parseCountList(match[1]);
    const survive = parseCountList(match[2]);
    const birthLookup = new Uint8Array(maxDegree + 1);
    const surviveLookup = new Uint8Array(maxDegree + 1);
    for (const value of birth) if (value <= maxDegree) birthLookup[value] = 1;
    for (const value of survive) if (value <= maxDegree) surviveLookup[value] = 1;
    const ignored = [...new Set([...birth, ...survive].filter((value) => value > maxDegree))]
      .sort((a, b) => a - b);
    return {
      text: formatRule(birth, survive),
      birth,
      survive,
      birthLookup,
      surviveLookup,
      ignored,
    };
  }

  function hashSeed(seed) {
    const text = String(seed);
    let h = 2166136261 >>> 0;
    for (let i = 0; i < text.length; i++) {
      h ^= text.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return h >>> 0;
  }

  function mulberry32(seed) {
    let state = seed >>> 0;
    return function () {
      state = (state + 0x6d2b79f5) | 0;
      let t = state;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  class Automaton {
    constructor(patch, graph, options = {}) {
      this.patch = patch;
      this.graph = graph;
      this.state = new Uint8Array(patch.tileCount);
      this.next = new Uint8Array(patch.tileCount);
      this.counts = new Uint8Array(patch.tileCount);
      this.liveList = new Uint32Array(patch.tileCount);
      this.liveLength = 0;
      this.liveListDirty = false;
      this.generation = 0;
      this.generations = clampInteger(options.generations, 2, 255, 2);
      this.borderRings = clampInteger(options.borderRings, 0, 0xffff, 0);
      this.boundaryDistance = graph.boundaryDistance || computeBoundaryDistance(graph.boundary || patch.boundary, graph);
      this.rule = parseRule(options.rule ?? 'B3/S23', graph.maxDegree);
      this.lastStepMilliseconds = 0;
      this.smoothedStepMilliseconds = 0;
      this.lastChangedCount = 0;
      this.stateHashA = 0;
      this.stateHashB = 0;
      this.hashDirty = true;
      this.refreshStateHash();
    }

    hashStateArray() {
      let hashA = 2166136261 >>> 0;
      let hashB = 0x9e3779b9 >>> 0;
      for (let i = 0; i < this.state.length; i++) {
        const token = (Math.imul(i + 1, 257) + this.state[i]) | 0;
        hashA = Math.imul(hashA ^ token, 16777619) >>> 0;
        hashB = Math.imul((hashB ^ token ^ (hashB >>> 16)) >>> 0, 2246822519) >>> 0;
      }
      return [hashA, hashB];
    }

    refreshStateHash() {
      const [hashA, hashB] = this.hashStateArray();
      this.stateHashA = hashA;
      this.stateHashB = hashB;
      this.hashDirty = false;
      return [hashA, hashB];
    }

    ensureStateHash() {
      return this.hashDirty ? this.refreshStateHash() : [this.stateHashA, this.stateHashB];
    }

    refreshDerivedState() {
      this.applyBorderMask();
      this.rebuildLiveList();
      this.refreshStateHash();
      return this.liveLength;
    }

    setGraph(graph) {
      const boundaryDistance = graph.boundaryDistance || computeBoundaryDistance(graph.boundary || this.patch.boundary, graph);
      const rule = parseRule(this.rule.text, graph.maxDegree);
      this.graph = graph;
      this.boundaryDistance = boundaryDistance;
      this.rule = rule;
      this.applyBorderMask();
      this.hashDirty = true;
    }

    setRule(text) {
      this.rule = parseRule(text, this.graph.maxDegree);
      return this.rule;
    }

    setGenerations(value) {
      this.generations = clampInteger(value, 2, 255, this.generations);
      for (let i = 0; i < this.state.length; i++) {
        if (this.state[i] >= this.generations) this.state[i] = 0;
      }
      this.liveListDirty = true;
      this.hashDirty = true;
      return this.generations;
    }

    setBorderRings(value) {
      this.borderRings = clampInteger(value, 0, 0xffff, this.borderRings);
      this.applyBorderMask();
      return this.borderRings;
    }

    isLocked(cell) {
      return this.borderRings > 0 && this.boundaryDistance[cell] < this.borderRings;
    }

    applyBorderMask() {
      if (this.borderRings <= 0) return;
      for (let i = 0; i < this.state.length; i++) {
        if (this.isLocked(i)) this.state[i] = 0;
      }
      this.liveListDirty = true;
      this.hashDirty = true;
    }

    clear() {
      this.state.fill(0);
      this.next.fill(0);
      this.liveLength = 0;
      this.liveListDirty = false;
      this.generation = 0;
      this.lastStepMilliseconds = 0;
      this.smoothedStepMilliseconds = 0;
      this.lastChangedCount = 0;
      this.refreshStateHash();
    }

    randomize(density, seed) {
      const numericDensity = Number(density);
      const probability = Number.isNaN(numericDensity)
        ? 0
        : Math.max(0, Math.min(1, numericDensity));
      const random = mulberry32(hashSeed(seed));
      this.liveLength = 0;
      for (let i = 0; i < this.state.length; i++) {
        const alive = !this.isLocked(i) && random() < probability;
        this.state[i] = alive ? 1 : 0;
        if (alive) this.liveList[this.liveLength++] = i;
      }
      this.next.fill(0);
      this.liveListDirty = false;
      this.generation = 0;
      this.lastStepMilliseconds = 0;
      this.smoothedStepMilliseconds = 0;
      this.lastChangedCount = 0;
      this.refreshStateHash();
    }

    setCell(cell, value) {
      if (!Number.isInteger(cell) || cell < 0 || cell >= this.state.length || this.isLocked(cell)) return false;
      const nextValue = value ? 1 : 0;
      if (this.state[cell] === nextValue) return false;
      this.state[cell] = nextValue;
      this.liveListDirty = true;
      this.hashDirty = true;
      return true;
    }

    rebuildLiveList() {
      this.liveLength = 0;
      for (let i = 0; i < this.state.length; i++) {
        if (this.state[i] === 1) this.liveList[this.liveLength++] = i;
      }
      this.liveListDirty = false;
    }

    aliveCount() {
      if (this.liveListDirty) this.rebuildLiveList();
      return this.liveLength;
    }

    step() {
      const started = typeof performance !== 'undefined' ? performance.now() : Date.now();
      if (this.liveListDirty) this.rebuildLiveList();
      const { offsets, neighbors } = this.graph;
      const n = this.state.length;
      this.counts.fill(0);

      for (let p = 0; p < this.liveLength; p++) {
        const cell = this.liveList[p];
        for (let k = offsets[cell]; k < offsets[cell + 1]; k++) {
          this.counts[neighbors[k]]++;
        }
      }

      let nextLiveLength = 0;
      let changedCount = 0;
      let hashA = 2166136261 >>> 0;
      let hashB = 0x9e3779b9 >>> 0;
      const generations = this.generations;
      const birth = this.rule.birthLookup;
      const survive = this.rule.surviveLookup;
      for (let i = 0; i < n; i++) {
        const previous = this.state[i];
        let value = previous;
        if (this.isLocked(i)) {
          value = 0;
        } else if (value === 0) {
          value = birth[this.counts[i]] ? 1 : 0;
        } else if (value === 1) {
          value = survive[this.counts[i]] ? 1 : generations > 2 ? 2 : 0;
        } else {
          value = value + 1 < generations ? value + 1 : 0;
        }
        this.next[i] = value;
        if (value !== previous) changedCount++;
        if (value === 1) this.liveList[nextLiveLength++] = i;
        const token = (Math.imul(i + 1, 257) + value) | 0;
        hashA = Math.imul(hashA ^ token, 16777619) >>> 0;
        hashB = Math.imul((hashB ^ token ^ (hashB >>> 16)) >>> 0, 2246822519) >>> 0;
      }

      const swap = this.state;
      this.state = this.next;
      this.next = swap;
      this.liveLength = nextLiveLength;
      this.liveListDirty = false;
      this.generation++;
      this.lastChangedCount = changedCount;
      this.stateHashA = hashA;
      this.stateHashB = hashB;
      this.hashDirty = false;

      const ended = typeof performance !== 'undefined' ? performance.now() : Date.now();
      this.lastStepMilliseconds = ended - started;
      this.smoothedStepMilliseconds =
        this.smoothedStepMilliseconds === 0
          ? this.lastStepMilliseconds
          : this.smoothedStepMilliseconds * 0.9 + this.lastStepMilliseconds * 0.1;
      return this.liveLength;
    }
  }

  function pointInTile(patch, tile, x, y) {
    if (
      !Number.isInteger(tile) ||
      tile < 0 ||
      tile >= patch.tileCount ||
      !Number.isFinite(x) ||
      !Number.isFinite(y)
    ) return false;
    const bboxOffset = tile * 4;
    if (
      x < patch.bboxes[bboxOffset] ||
      x > patch.bboxes[bboxOffset + 2] ||
      y < patch.bboxes[bboxOffset + 1] ||
      y > patch.bboxes[bboxOffset + 3]
    ) {
      return false;
    }

    let inside = false;
    const n = patch.verticesPerTile;
    const base = tile * n * 2;
    for (let i = 0, j = n - 1; i < n; j = i++) {
      const xi = patch.vertices[base + i * 2];
      const yi = patch.vertices[base + i * 2 + 1];
      const xj = patch.vertices[base + j * 2];
      const yj = patch.vertices[base + j * 2 + 1];
      const dx = xj - xi;
      const dy = yj - yi;
      const scale = Math.abs(dx) + Math.abs(dy) + 1;
      const cross = (x - xi) * dy - (y - yi) * dx;
      const dot = (x - xi) * dx + (y - yi) * dy;
      const lengthSquared = dx * dx + dy * dy;
      const tolerance = 1e-6 * scale;
      if (Math.abs(cross) <= tolerance && dot >= -tolerance && dot <= lengthSquared + tolerance) {
        return true;
      }
      const crosses = yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
      if (crosses) inside = !inside;
    }
    return inside;
  }

  class PickingIndex {
    constructor(patch, cellSize = 2) {
      if (!Number.isFinite(cellSize) || cellSize <= 0) {
        throw new RangeError('cellSize must be a positive finite number');
      }
      this.patch = patch;
      this.cellSize = cellSize;
      this.buckets = new Map();
      this.bias = 1 << 15;
      this.base = 1 << 16;
      const assignmentLimit = Math.max(100000, patch.tileCount * 32);
      let assignments = 0;

      for (let tile = 0; tile < patch.tileCount; tile++) {
        const o = tile * 4;
        const gx0 = Math.floor(patch.bboxes[o] / cellSize);
        const gy0 = Math.floor(patch.bboxes[o + 1] / cellSize);
        const gx1 = Math.floor(patch.bboxes[o + 2] / cellSize);
        const gy1 = Math.floor(patch.bboxes[o + 3] / cellSize);
        if (
          !Number.isSafeInteger(gx0) || !Number.isSafeInteger(gy0) ||
          !Number.isSafeInteger(gx1) || !Number.isSafeInteger(gy1) ||
          gx0 < -this.bias || gy0 < -this.bias ||
          gx1 >= this.bias || gy1 >= this.bias
        ) {
          throw new RangeError('cellSize produces a picking grid outside the supported coordinate range');
        }
        const spanX = gx1 - gx0 + 1;
        const spanY = gy1 - gy0 + 1;
        assignments += spanX * spanY;
        if (!Number.isSafeInteger(assignments) || assignments > assignmentLimit) {
          throw new RangeError('cellSize produces too many picking-grid assignments');
        }
        for (let gx = gx0; gx <= gx1; gx++) {
          for (let gy = gy0; gy <= gy1; gy++) {
            const key = this.key(gx, gy);
            let bucket = this.buckets.get(key);
            if (!bucket) this.buckets.set(key, (bucket = []));
            bucket.push(tile);
          }
        }
      }
    }

    key(gx, gy) {
      return (gx + this.bias) * this.base + (gy + this.bias);
    }

    find(x, y) {
      if (!Number.isFinite(x) || !Number.isFinite(y)) return -1;
      const gx = Math.floor(x / this.cellSize);
      const gy = Math.floor(y / this.cellSize);
      if (gx < -this.bias || gy < -this.bias || gx >= this.bias || gy >= this.bias) return -1;
      const bucket = this.buckets.get(this.key(gx, gy));
      if (!bucket) return -1;
      for (let i = bucket.length - 1; i >= 0; i--) {
        if (pointInTile(this.patch, bucket[i], x, y)) return bucket[i];
      }
      return -1;
    }
  }

