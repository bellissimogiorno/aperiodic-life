  class MetaTile {
    constructor(shape, width) {
      this.shape = shape;
      this.width = width;
      this.children = [];
      this.kind = 'meta';
    }

    addChild(T, geom) {
      this.children.push({ T, geom });
    }

    evalChild(childIndex, vertexIndex) {
      const child = this.children[childIndex];
      return transformPoint(child.T, child.geom.shape[vertexIndex]);
    }

    recentre() {
      let cx = 0;
      let cy = 0;
      for (const p of this.shape) {
        cx += p.x;
        cy += p.y;
      }
      cx /= this.shape.length;
      cy /= this.shape.length;
      const shift = pt(-cx, -cy);
      this.shape = this.shape.map((p) => padd(p, shift));
      const M = translation(-cx, -cy);
      for (const child of this.children) child.T = multiply(M, child.T);
    }
  }

