  function invert(T) {
    const det = T[0] * T[4] - T[1] * T[3];
    if (Math.abs(det) < 1e-14) throw new Error('Singular affine transform');
    return [
      T[4] / det,
      -T[1] / det,
      (T[1] * T[5] - T[2] * T[4]) / det,
      -T[3] / det,
      T[0] / det,
      (T[2] * T[3] - T[0] * T[5]) / det,
    ];
  }

  function multiply(A, B) {
    return [
      A[0] * B[0] + A[1] * B[3],
      A[0] * B[1] + A[1] * B[4],
      A[0] * B[2] + A[1] * B[5] + A[2],
      A[3] * B[0] + A[4] * B[3],
      A[3] * B[1] + A[4] * B[4],
      A[3] * B[2] + A[4] * B[5] + A[5],
    ];
  }

  function rotation(angle) {
    const c = Math.cos(angle);
    const s = Math.sin(angle);
    return [c, -s, 0, s, c, 0];
  }

  const translation = (x, y) => [1, 0, x, 0, 1, y];

  function rotateAbout(p, angle) {
    return multiply(
      translation(p.x, p.y),
      multiply(rotation(angle), translation(-p.x, -p.y)),
    );
  }

  function transformPoint(M, P) {
    return pt(
      M[0] * P.x + M[1] * P.y + M[2],
      M[3] * P.x + M[4] * P.y + M[5],
    );
  }

  function matchSegment(p, q) {
    return [q.x - p.x, p.y - q.y, p.x, q.y - p.y, q.x - p.x, p.y];
  }

  function matchTwo(p1, q1, p2, q2) {
    return multiply(matchSegment(p2, q2), invert(matchSegment(p1, q1)));
  }

  function intersectLines(p1, q1, p2, q2) {
    const d =
      (q2.y - p2.y) * (q1.x - p1.x) -
      (q2.x - p2.x) * (q1.y - p1.y);
    if (Math.abs(d) < 1e-14) throw new Error('Parallel lines in substitution geometry');
    const uA =
      ((q2.x - p2.x) * (p1.y - p2.y) -
        (q2.y - p2.y) * (p1.x - p2.x)) /
      d;
    return pt(p1.x + uA * (q1.x - p1.x), p1.y + uA * (q1.y - p1.y));
  }

